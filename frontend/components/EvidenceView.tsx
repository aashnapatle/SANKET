"use client";
import { useState } from "react";
import { useSanketStore } from "@/lib/store";
import { RiskBadge, EmptyState } from "@/components/ui";
import { formatCurrencyFull, formatTimestamp, getRiskColor, cn } from "@/lib/utils";
import type { InvestigationResponse, EvidenceItem } from "@/lib/types";
import { ChevronDown, ChevronRight, Shield, ExternalLink } from "lucide-react";

interface EvidenceViewProps {
  investigation: InvestigationResponse;
}

export default function EvidenceView({ investigation }: EvidenceViewProps) {
  const { evidence, transactions } = investigation;
  const { activeSignalId } = useSanketStore();
  const [expandedIds, setExpandedIds] = useState<Set<string>>(
    new Set(activeSignalId ? [evidence.find(e => e.signal.toLowerCase().includes(activeSignalId))?.id ?? ""] : [])
  );

  if (!evidence.length) {
    return (
      <div className="flex items-center justify-center h-full">
        <EmptyState
          icon={<Shield size={20} />}
          title="No evidence collected"
          description="Evidence is generated by the backend risk analysis engine based on detected suspicious patterns."
        />
      </div>
    );
  }

  const toggleExpand = (id: string) => {
    setExpandedIds(prev => {
      const next = new Set(prev);
      if (next.has(id)) next.delete(id);
      else next.add(id);
      return next;
    });
  };

  const getTransaction = (id: string) => transactions.find(t => t.transaction_id === id);

  return (
    <div className="h-full flex flex-col overflow-hidden">
      {/* ─── Header ───────────────────────────────────── */}
      <div className="flex items-center justify-between px-4 py-2.5 border-b border-[#e8d8c4] bg-[#fdf8f3] flex-shrink-0">
        <div className="flex items-center gap-2">
          <Shield size={14} className="text-[#5c3d1e]" />
          <span className="text-sm font-semibold text-[#2c1810]">Evidence</span>
          <span className="text-xs text-[#8c6e4e] bg-[#f0e8dc] px-2 py-0.5 rounded-full">
            {evidence.length} items
          </span>
        </div>
        <button
          onClick={() => setExpandedIds(new Set(evidence.map(e => e.id)))}
          className="text-xs text-[#5c3d1e] hover:underline"
        >
          Expand all
        </button>
      </div>

      {/* ─── Evidence List ────────────────────────────── */}
      <div className="flex-1 overflow-y-auto p-4 space-y-3">
        {/* Column headers */}
        <div className="grid grid-cols-5 gap-2 px-3 py-1.5 text-[10px] font-semibold text-[#8c6e4e] uppercase tracking-wider border-b border-[#e8d8c4]">
          <span>ID</span>
          <span className="col-span-2">Signal</span>
          <span>Transactions</span>
          <span>Risk</span>
        </div>

        {evidence.map(ev => {
          const isExpanded = expandedIds.has(ev.id);
          const supportingTxns = ev.transactions.map(id => getTransaction(id)).filter(Boolean);

          return (
            <div
              key={ev.id}
              className="bg-white border border-[#e8d8c4] rounded-xl overflow-hidden shadow-sm transition-all duration-200"
            >
              {/* ─── Header row ─────────────────────────────── */}
              <button
                onClick={() => toggleExpand(ev.id)}
                className="w-full flex items-center gap-3 px-4 py-3 text-left hover:bg-[#faf6f1] transition-colors group"
              >
                <span className="flex-shrink-0 text-[#8c6e4e] transition-transform duration-200" style={{ transform: isExpanded ? "rotate(0deg)" : "rotate(-90deg)" }}>
                  <ChevronDown size={14} />
                </span>
                <span className="font-mono text-xs text-[#8c6e4e] w-16 flex-shrink-0">{ev.id}</span>
                <span className="flex-1 text-sm font-semibold text-[#2c1810]">{ev.signal}</span>
                <span className="text-xs text-[#8c6e4e] flex-shrink-0">
                  {ev.transactions.join(", ")}
                </span>
                <RiskBadge level={ev.risk_level} size="sm" />
              </button>

              {/* ─── Expanded content ─────────────────────────── */}
              {isExpanded && (
                <div className="border-t border-[#e8d8c4] px-4 py-3 fade-in">
                  <p className="text-sm text-[#5c3d1e] mb-3 leading-relaxed">{ev.description}</p>

                  {supportingTxns.length > 0 && (
                    <div className="space-y-2">
                      <div className="text-xs font-semibold text-[#8c6e4e] uppercase tracking-wide mb-2">
                        Supporting Transactions
                      </div>
                      {supportingTxns.map(tx => tx && (
                        <div key={tx.transaction_id} className="bg-[#faf6f1] rounded-lg p-3 flex items-start gap-3 border border-[#f0e8dc]">
                          <div className="flex-1 min-w-0">
                            <div className="flex items-center gap-2 mb-1">
                              <span className="font-mono text-[10px] text-[#8c6e4e]">{tx.transaction_id}</span>
                              <RiskBadge level={tx.risk_level || "Low"} size="sm" />
                            </div>
                            <div className="text-xs font-medium text-[#2c1810]">
                              {tx.sender_account} → {tx.receiver_account}
                            </div>
                            <div className="flex items-center gap-2 mt-0.5">
                              <span className="text-sm font-bold text-[#2c1810]">
                                {formatCurrencyFull(tx.amount)}
                              </span>
                              <span className="text-xs text-[#8c6e4e]">
                                {tx.payment_mode} · {new Date(tx.timestamp).toLocaleString("en-IN", { hour: "2-digit", minute: "2-digit", month: "short", day: "numeric" })}
                              </span>
                            </div>
                            {(tx.device_type === "WEB_EMULATOR" || tx.device_type === "LINUX_SCRIPT") && (
                              <div className="mt-1.5 text-[10px] text-[#c0392b] bg-[#fdf0ef] border border-[#f1b4b0] rounded-md px-2 py-1 inline-block">
                                ⚠ Suspicious device: {tx.device_type}
                              </div>
                            )}
                          </div>
                        </div>
                      ))}
                    </div>
                  )}

                  {/* Elapsed time between transactions */}
                  {supportingTxns.length >= 2 && (
                    <div className="mt-3 text-xs text-[#8c6e4e] bg-[#f5f0eb] rounded-lg px-3 py-2">
                      <span className="font-medium">Elapsed: </span>
                      {(() => {
                        const first = new Date(supportingTxns[0]!.timestamp).getTime();
                        const last = new Date(supportingTxns[supportingTxns.length - 1]!.timestamp).getTime();
                        const diffSec = Math.round((last - first) / 1000);
                        return diffSec < 60 ? `${diffSec} seconds` : `${Math.floor(diffSec / 60)} minutes ${diffSec % 60} seconds`;
                      })()}
                    </div>
                  )}
                </div>
              )}
            </div>
          );
        })}
      </div>
    </div>
  );
}
